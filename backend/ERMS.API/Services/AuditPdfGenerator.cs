using System.Text;
using ERMS.API.DTOs;

namespace ERMS.API.Services;

/// <summary>
/// Native lightweight PDF generator for formatting and rendering official Audit Log Reports.
/// Generates standards-compliant PDF 1.4 documents without external third-party dependencies.
/// </summary>
public static class AuditPdfGenerator
{
    public static byte[] GenerateAuditReportPdf(
        IReadOnlyList<AuditLogDto> logs,
        string generatedBy,
        DateTime generatedAtUtc)
    {
        var sb = new StringBuilder();

        // Escape text for PDF string literals
        static string EscapePdf(string? input)
        {
            if (string.IsNullOrEmpty(input)) return "-";
            return input
                .Replace("\\", "\\\\")
                .Replace("(", "\\(")
                .Replace(")", "\\)")
                .Replace("\r", " ")
                .Replace("\n", " ");
        }

        // Divide logs into pages (25 items per page)
        const int itemsPerPage = 25;
        var pages = new List<List<AuditLogDto>>();
        if (logs.Count == 0)
        {
            pages.Add(new List<AuditLogDto>());
        }
        else
        {
            for (int i = 0; i < logs.Count; i += itemsPerPage)
            {
                pages.Add(logs.Skip(i).Take(itemsPerPage).ToList());
            }
        }

        int totalPages = pages.Count;
        var pageStreams = new List<string>();

        for (int p = 0; p < totalPages; p++)
        {
            var pageLogs = pages[p];
            var streamContent = new StringBuilder();

            // Header Banner & Metadata
            streamContent.AppendLine("BT");
            streamContent.AppendLine("/F2 16 Tf"); // Helvetica-Bold 16pt
            streamContent.AppendLine("40 750 Td");
            streamContent.AppendLine($"(EMPLOYEE RECORDS MANAGEMENT SYSTEM \\(ERMS\\)) Tj");
            streamContent.AppendLine("ET");

            streamContent.AppendLine("BT");
            streamContent.AppendLine("/F2 12 Tf"); // Helvetica-Bold 12pt
            streamContent.AppendLine("40 730 Td");
            streamContent.AppendLine($"(OFFICIAL SECURITY AUDIT TRAIL EXPORT) Tj");
            streamContent.AppendLine("ET");

            streamContent.AppendLine("BT");
            streamContent.AppendLine("/F1 8 Tf"); // Helvetica 8pt
            streamContent.AppendLine("40 715 Td");
            streamContent.AppendLine($"(Generated By: {EscapePdf(generatedBy)} | Export Time: {generatedAtUtc:yyyy-MM-dd HH:mm:ss} UTC | Page {p + 1} of {totalPages}) Tj");
            streamContent.AppendLine("ET");

            // Horizontal Divider Rule
            streamContent.AppendLine("0.5 w");
            streamContent.AppendLine("40 705 m 572 705 l S");

            // Table Header Row
            streamContent.AppendLine("BT");
            streamContent.AppendLine("/F2 8 Tf");
            streamContent.AppendLine("40 690 Td (TIMESTAMP) Tj");
            streamContent.AppendLine("90 0 Td (ACTOR / IDENTITY) Tj");
            streamContent.AppendLine("120 0 Td (ACTION / TYPE) Tj");
            streamContent.AppendLine("120 0 Td (RESOURCE) Tj");
            streamContent.AppendLine("110 0 Td (STATUS) Tj");
            streamContent.AppendLine("50 0 Td (IP ADDRESS) Tj");
            streamContent.AppendLine("ET");

            streamContent.AppendLine("0.25 w");
            streamContent.AppendLine("40 682 m 572 682 l S");

            // Table Data Rows
            double currentY = 668;
            foreach (var log in pageLogs)
            {
                string timeStr = log.Timestamp.ToString("yyyy-MM-dd HH:mm");
                string actorStr = log.UserIdentity ?? "System";
                if (actorStr.Length > 20) actorStr = actorStr[..18] + "..";

                string actionStr = $"{log.Category}: {log.ActivityType}";
                if (actionStr.Length > 22) actionStr = actionStr[..20] + "..";

                string resourceStr = log.TargetResource ?? "-";
                if (resourceStr.Length > 22) resourceStr = resourceStr[..20] + "..";

                string resultStr = log.ActionResult;
                string ipStr = log.IpAddress ?? "-";
                if (ipStr.Length > 15) ipStr = ipStr[..13] + "..";

                streamContent.AppendLine("BT");
                streamContent.AppendLine("/F1 7 Tf");
                streamContent.AppendLine($"40 {currentY:F0} Td ({EscapePdf(timeStr)}) Tj");
                streamContent.AppendLine($"90 0 Td ({EscapePdf(actorStr)}) Tj");
                streamContent.AppendLine($"120 0 Td ({EscapePdf(actionStr)}) Tj");
                streamContent.AppendLine($"120 0 Td ({EscapePdf(resourceStr)}) Tj");
                streamContent.AppendLine($"110 0 Td ({EscapePdf(resultStr)}) Tj");
                streamContent.AppendLine($"50 0 Td ({EscapePdf(ipStr)}) Tj");
                streamContent.AppendLine("ET");

                currentY -= 20;
            }

            // Footer
            streamContent.AppendLine("0.25 w");
            streamContent.AppendLine("40 45 m 572 45 l S");
            streamContent.AppendLine("BT");
            streamContent.AppendLine("/F1 7 Tf");
            streamContent.AppendLine("40 32 Td (CONFIDENTIAL - ERMS Information Assurance & Security Audit Record - Tamper-evident Archive) Tj");
            streamContent.AppendLine("ET");

            pageStreams.Add(streamContent.ToString());
        }

        // Construct PDF Objects
        var objects = new List<string>();

        // 1: Catalog
        objects.Add("<< /Type /Catalog /Pages 2 0 R >>");

        // 2: Pages root
        var pageRefs = string.Join(" ", Enumerable.Range(0, totalPages).Select(i => $"{6 + i * 2} 0 R"));
        objects.Add($"<< /Type /Pages /Kids [{pageRefs}] /Count {totalPages} >>");

        // 3: Font Helvetica
        objects.Add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");

        // 4: Font Helvetica-Bold
        objects.Add("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>");

        // 5: ProcSet
        objects.Add("[/PDF /Text]");

        // For each page: Page object + Stream object
        for (int i = 0; i < totalPages; i++)
        {
            int pageObjNum = 6 + i * 2;
            int streamObjNum = pageObjNum + 1;
            string pageContent = pageStreams[i];
            byte[] contentBytes = Encoding.ASCII.GetBytes(pageContent);

            // Page Object
            objects.Add($"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> /ProcSet 5 0 R >> /Contents {streamObjNum} 0 R >>");

            // Stream Object
            objects.Add($"<< /Length {contentBytes.Length} >>\nstream\n{pageContent}\nendstream");
        }

        // Assemble Final PDF bytes with xref and trailer
        using var ms = new MemoryStream();
        using var writer = new StreamWriter(ms, Encoding.ASCII);

        writer.Write("%PDF-1.4\n%\xE2\xE3\xCF\xD3\n");
        writer.Flush();

        var offsets = new List<long>();
        for (int i = 0; i < objects.Count; i++)
        {
            offsets.Add(ms.Position);
            writer.Write($"{i + 1} 0 obj\n{objects[i]}\nendobj\n");
            writer.Flush();
        }

        long xrefStart = ms.Position;
        writer.Write($"xref\n0 {objects.Count + 1}\n0000000000 65535 f \n");
        foreach (var offset in offsets)
        {
            writer.Write($"{offset:D10} 00000 n \n");
        }

        writer.Write($"trailer\n<< /Size {objects.Count + 1} /Root 1 0 R >>\nstartxref\n{xrefStart}\n%%EOF\n");
        writer.Flush();

        return ms.ToArray();
    }
}
